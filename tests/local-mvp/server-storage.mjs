import assert from 'node:assert/strict';
import { mkdtemp,rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { UserStorage } from '../../src/lib/server/database/storage.ts';
import { openDatabase } from '../../src/lib/server/database/sqlite.ts';
import { encodeWire,decodeWire } from '../../src/lib/db/wire.ts';
const directory=await mkdtemp(join(tmpdir(),'utsuwa-storage-test-'));
try{
 let store=new UserStorage(directory);
 const run=async(user,body)=>decodeWire(store.run(user,await encodeWire(body)));
 const id=await run('alice',{op:'add',collection:'conversationTurns',value:{role:'user',content:'仅属于 Alice',createdAt:new Date()}});
 assert.equal((await run('alice',{op:'get',collection:'conversationTurns',id})).content,'仅属于 Alice');
 assert.equal(await run('bob',{op:'get',collection:'conversationTurns',id}),null);
 await run('bob',{op:'update',collection:'conversationTurns',id,value:{content:'wrong'}});
 assert.equal((await run('alice',{op:'get',collection:'conversationTurns',id})).content,'仅属于 Alice');
 await run('alice',{op:'kvSet',store:'preferences',key:'utsuwa-display',value:'light'});
 assert.deepEqual(store.preferences('bob'),{});
 await run('alice',{op:'kvSet',store:'utsuwa-keepsakes',key:'photo',value:new Blob(['private photo'],{type:'image/png'})});
 const photo=await run('alice',{op:'kvGet',store:'utsuwa-keepsakes',key:'photo'});assert.equal(await photo.text(),'private photo');
 const reminder=await run('alice',{op:'add',collection:'reminders',value:{triggerAt:new Date(),executed:0}});
 const expected=await run('alice',{op:'get',collection:'reminders',id:reminder});assert.ok(expected.triggerAt instanceof Date);
 assert.equal(await run('alice',{op:'modify',collection:'reminders',items:[{id:reminder,expected}],value:{executed:1}}),1);
 assert.equal(await run('alice',{op:'modify',collection:'reminders',items:[{id:reminder,expected}],value:{executed:1}}),0);
 store=new UserStorage(directory);assert.equal((await run('alice',{op:'list',collection:'conversationTurns'})).length,1);
 await run('bob',{op:'clearAll'});assert.equal((await run('alice',{op:'list',collection:'conversationTurns'})).length,1);
 await run('alice',{op:'clearAll'});assert.equal((await run('alice',{op:'list',collection:'conversationTurns'})).length,0);
 assert.throws(()=>store.run('alice',{op:'list',collection:'auth_users'}));
 const legacy={op:'migrate',records:{sessions:[{id:8,startedAt:new Date()}],conversationTurns:[{id:4,sessionId:8,content:'legacy'}]},preferences:{colorMode:'light'},assets:[]};
 const migrated=await run('migrant',legacy);assert.equal(migrated.imported,2);
 const turns=await run('migrant',{op:'list',collection:'conversationTurns'});const sessions=await run('migrant',{op:'list',collection:'sessions'});assert.equal(turns[0].sessionId,sessions[0].id);
 assert.equal((await run('migrant',legacy)).alreadyMigrated,true);
 await assert.rejects(run('rollback',{op:'migrate',records:{facts:[{content:'must rollback'}]},assets:[{store:'invalid',key:'x',value:'bad'}]}));
 assert.equal((await run('rollback',{op:'list',collection:'facts'})).length,0);
 const snap=await run('atomic',{op:'snapshot'});
 await run('atomic',{op:'add',collection:'facts',value:{content:'newer live data'}});
 await assert.rejects(run('atomic',{op:'commitSnapshot',...snap}),e=>e.status===409);
 assert.equal((await run('atomic',{op:'list',collection:'facts'})).length,1);
 const fresh=await run('atomic',{op:'snapshot'});fresh.records.facts=[{id:7,content:'imported'}];await run('atomic',{op:'commitSnapshot',...fresh});
 assert.equal((await run('atomic',{op:'get',collection:'facts',id:7})).content,'imported');
 console.log('PASS: SQLite persistence, account isolation, private assets, Dates, atomic reminder claims and scoped deletion.');
}finally{openDatabase(join(directory,'utsuwa.sqlite')).close();await rm(directory,{recursive:true,force:true});}
